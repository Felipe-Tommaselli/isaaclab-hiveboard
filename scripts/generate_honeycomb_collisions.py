#!/usr/bin/env python3
"""Bake hollow-cell HiveBoard colliders without filling the hexagonal openings.

Run with ``uv run python scripts/generate_honeycomb_collisions.py``. The CAD
cells have a 5 mm mounting lip and a 20 mm outer wall. Each hexagonal ring is
split into six convex prisms, preserving both the hole and the stepped lip.
Dimensions and cell transforms come from the bundled visual USD, in millimetres.
"""

from pathlib import Path

import numpy as np
from pxr import Gf, Usd, UsdGeom, UsdPhysics

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "source/isaaclab_hiveboard/isaaclab_hiveboard/assets/hiveboard/honeycomb"


def generate(destination: Path = ASSETS / "Honeycomb_Panel_Collision.usda") -> None:
    source = Usd.Stage.Open(str(ASSETS / "Honeycomb_Panel.usd"))
    cells = [prim for prim in source.Traverse() if prim.IsA(UsdGeom.Mesh)]
    points = np.unique(np.round(UsdGeom.Mesh(cells[0]).GetPointsAttr().Get(), 5), axis=0)
    radii = np.unique(np.round(np.linalg.norm(points[:, :2], axis=1), 4))
    depths = np.unique(points[:, 2])
    if len(cells) != 7 or len(radii) != 3 or not np.allclose(depths, (0.0, 5.0, 20.0)):
        raise ValueError("Honeycomb CAD topology changed; review the ring decomposition.")

    stage = Usd.Stage.CreateNew(str(destination))
    root = UsdGeom.Xform.Define(stage, "/Honeycomb_Panel")
    root.GetPrim().GetReferences().AddReference("./Honeycomb_Panel.usd")
    stage.SetDefaultPrim(root.GetPrim())
    UsdGeom.SetStageMetersPerUnit(stage, 0.001)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    stage.GetRootLayer().documentation = "Generated by scripts/generate_honeycomb_collisions.py"
    cache = UsdGeom.XformCache()
    # Outward-wound prism faces: bottom, top, then the four side faces.
    faces = (0, 3, 2, 1, 4, 5, 6, 7, 0, 1, 5, 4, 1, 2, 6, 5, 2, 3, 7, 6, 3, 0, 4, 7)
    for cell_index, cell in enumerate(cells):
        path = f"/Honeycomb_Panel/Collisions/Cell_{cell_index}"
        cell_root = UsdGeom.Xform.Define(stage, path)
        if cell_index:
            cell_root.GetPrim().GetReferences().AddInternalReference("/Honeycomb_Panel/Collisions/Cell_0")
        cell_root.ClearXformOpOrder()
        cell_root.AddTransformOp().Set(cache.GetLocalToWorldTransform(cell))
        if cell_index:
            continue
        for ring_index, (inner, outer, depth) in enumerate(
            ((radii[0], radii[1], depths[1]), (radii[1], radii[2], depths[2]))
        ):
            for edge in range(6):
                angles = np.radians((edge * 60, (edge + 1) * 60))
                xy = np.array([
                    [radius * np.cos(angle), radius * np.sin(angle)]
                    for radius, angle in ((inner, angles[0]), (outer, angles[0]),
                                          (outer, angles[1]), (inner, angles[1]))
                ])
                vertices = [Gf.Vec3f(float(x), float(y), float(z)) for z in (0.0, depth) for x, y in xy]
                mesh = UsdGeom.Mesh.Define(stage, f"{path}/ring_{ring_index}_edge_{edge}")
                mesh.CreatePointsAttr(vertices)
                mesh.CreateFaceVertexCountsAttr([4] * 6)
                mesh.CreateFaceVertexIndicesAttr(faces)
                mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
                mesh.CreateVisibilityAttr(UsdGeom.Tokens.invisible)
                UsdPhysics.CollisionAPI.Apply(mesh.GetPrim()).CreateCollisionEnabledAttr(True)
                UsdPhysics.MeshCollisionAPI.Apply(mesh.GetPrim()).CreateApproximationAttr("convexHull")
    stage.GetRootLayer().Save()
    print(f"Wrote {destination}: 7 cells, 84 convex prisms, open hexagonal centres.")


if __name__ == "__main__":
    generate()
